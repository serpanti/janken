"""Reproduce test fixtures using public CGI images, never a physical camera.

Source: Laurence Moroney, Rock Paper Scissors, CC BY 2.0 (see NOTICE.md).
Uses the official TensorFlow test archive and the application's unchanged model.
"""
from pathlib import Path
import json
import urllib.request
import zipfile
import cv2
import numpy as np
import mediapipe as mp
from mediapipe.tasks.python import BaseOptions, vision

ROOT = Path(__file__).resolve().parents[1]
URL = 'https://storage.googleapis.com/download.tensorflow.org/data/rps-test-set.zip'


def main():
    work = ROOT / '.work'
    work.mkdir(exist_ok=True)
    archive = work / 'rps-test-set.zip'
    if not archive.is_file():
        urllib.request.urlretrieve(URL, archive)
    options = vision.GestureRecognizerOptions(base_options=BaseOptions(
        model_asset_buffer=(ROOT / 'models/gesture_recognizer.task').read_bytes()), num_hands=1)
    cases = []
    with zipfile.ZipFile(archive) as images, vision.GestureRecognizer.create_from_options(options) as recognizer:
        for label in ['rock', 'paper', 'scissors']:
            for hand in range(1, 5):
                name = f'rps-test-set/{label}/test{label}{hand:02}-00.png'
                data = images.read(name)
                rgb = cv2.cvtColor(cv2.imdecode(np.frombuffer(data, np.uint8), cv2.IMREAD_COLOR), cv2.COLOR_BGR2RGB)
                result = recognizer.recognize(mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb))
                category = max(result.gestures[0], key=lambda c: c.score) if result.gestures else None
                world = result.hand_world_landmarks[0] if result.hand_world_landmarks else []
                image = result.hand_landmarks[0] if result.hand_landmarks else []
                assert len(world) == len(image) == 21, f'No complete landmarks: {name}'
                cases.append({'name': name, 'expected': label,
                              'label': category.category_name if category else None,
                              'score': float(category.score) if category else 0,
                              'worldPoints': [{a: round(getattr(p, a), 7) for a in ['x', 'y', 'z']} for p in world],
                              'points': [{a: round(getattr(p, a), 7) for a in ['x', 'y']} for p in image],
                              'width': rgb.shape[1], 'height': rgb.shape[0]})
                destination = ROOT / 'app/src/androidTest/assets/dorsal' / Path(name).name
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(data)
    body = ',\n'.join(json.dumps(c, separators=(',', ':')) for c in cases)
    destination = ROOT / 'camera/src/commonTest/kotlin/dev/janken/camera/DorsalHandFixtures.kt'
    destination.write_text('// Generated by tools/prepare_dorsal_fixtures.py.\n'
        '// SDK outputs from Laurence Moroney CGI Rock Paper Scissors test images, CC BY 2.0.\n'
        '// See NOTICE.md. No physical camera.\npackage dev.janken.camera\n\n'
        'internal val dorsalHandCases = """[\n' + body + '\n]"""\n', encoding='utf-8')
    print(f'Generated {len(cases)} dorsal-view SDK fixtures.')


if __name__ == '__main__':
    main()
