"""Capture SDK landmarks from the public Google fixtures, never a webcam."""
from pathlib import Path
import json
import cv2
import numpy as np
import mediapipe as mp
from mediapipe.tasks.python import BaseOptions, vision

ROOT = Path(__file__).resolve().parents[1]


def main():
    cases = []
    model = (ROOT / 'models/gesture_recognizer.task').read_bytes()
    options = vision.GestureRecognizerOptions(base_options=BaseOptions(model_asset_buffer=model), num_hands=1)
    with vision.GestureRecognizer.create_from_options(options) as recognizer:
        for name in ['fist', 'victory', 'right_hands', 'thumb_up']:
            # OpenCV imread does not reliably handle Unicode paths on Windows.
            frame = cv2.imdecode(np.fromfile(ROOT / f'app/src/androidTest/assets/{name}.jpg', dtype=np.uint8), cv2.IMREAD_COLOR)
            for turns in range(4):
                rgb = np.ascontiguousarray(np.rot90(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB), turns))
                result = recognizer.recognize(mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb))
                category = max(result.gestures[0], key=lambda c: c.score) if result.gestures else None
                points = result.hand_world_landmarks[0] if result.hand_world_landmarks else []
                metrics = []
                for base in [5, 9, 13, 17] if points else []:
                    p = [np.array([points[i].x, points[i].y, points[i].z]) for i in range(base, base + 4)]
                    def cosine(a, b):
                        return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b)))
                    metrics.append([round(float(np.linalg.norm(p[3] - p[0]) / sum(np.linalg.norm(p[i + 1] - p[i]) for i in range(3))), 3),
                                    round(cosine(p[0] - p[1], p[2] - p[1]), 3), round(cosine(p[1] - p[2], p[3] - p[2]), 3)])
                label = category.category_name if category else None
                print(name, turns * 90, label, round(category.score, 2) if category else 0, metrics)
                cases.append({'name': f'{name}_{turns * 90}', 'label': label, 'score': float(category.score) if category else 0,
                              'worldPoints': [{'x': p.x, 'y': p.y, 'z': p.z} for p in points],
                              'points': [{'x': p.x, 'y': p.y} for p in (result.hand_landmarks[0] if result.hand_landmarks else [])],
                              'width': rgb.shape[1], 'height': rgb.shape[0]})
    for case in cases:
        if len(case['worldPoints']) != 21:
            raise RuntimeError(f"No complete hand in fixture {case['name']}")
        case['score'] = round(case['score'], 7)
        for key in ['points', 'worldPoints']:
            case[key] = [{axis: round(value, 7) for axis, value in p.items()} for p in case[key]]
    (ROOT / '.work/rps-landmark-cases.json').write_text(json.dumps(cases), encoding='utf-8')
    fixture = ROOT / 'camera/src/commonTest/kotlin/dev/janken/camera/HandShapeFixtures.kt'
    body = ',\n'.join(json.dumps(case, separators=(',', ':')) for case in cases)
    fixture.write_text('// Generated by tools/prepare_hand_shape_fixtures.py from public Google fixtures (see NOTICE.md).\n'
                       '// Each image was actually run through MediaPipe at 0, 90, 180 and 270 degrees.\n'
                       'package dev.janken.camera\n\ninternal val recordedHandCases = """[\n' + body + '\n]"""\n', encoding='utf-8')


if __name__ == '__main__':
    main()
